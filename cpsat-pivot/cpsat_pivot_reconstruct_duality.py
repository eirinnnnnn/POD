def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("npz", nargs="?", default=None,
                        help="Optional .npz file containing Gb, Gp, p_star.")
    parser.add_argument("--time", type=float, default=60.0,
                        help="CP-SAT time limit in seconds.")
    parser.add_argument("--workers", "--worker", type=int, default=8,
                        help="Number of CP-SAT search workers.")
    parser.add_argument("--log", action="store_true",
                        help="Enable CP-SAT search log.")
    parser.add_argument("--print-matrices", action="store_true",
                        help="Print pi(Gb), W, U, M after solving.")
    parser.add_argument("--w-encoding", choices=["auto", "butterfly", "dense"],
                        default="auto")
    parser.add_argument("--certificate", choices=["pivot-only", "full"],
                        default="pivot-only",
                        help="pivot-only: U-certificate on pivot columns + "
                             "span membership (equivalent, much smaller). "
                             "full: v1 model.")
    parser.add_argument("--rank-cuts", choices=["none", "prefix-zero", "span"],
                        default="span",
                        help="Only used with --certificate full.")
    parser.add_argument("--dualize", choices=["auto", "always", "never"],
                        default="auto",
                        help="Solve the (n-k)-row dual instance when smaller.")
    parser.add_argument("--branch", choices=["popcount", "first"],
                        default="popcount",
                        help="pi branching order (popcount: descending "
                             "popcount of position index).")
    parser.add_argument("--no-row-weight-cuts", action="store_true",
                        help="Disable redundant row-weight constraints.")
    parser.add_argument("--skip-duality-selftest", action="store_true",
                        help="Skip the numeric duality self-test.")
    args = parser.parse_args()

    if not args.skip_duality_selftest:
        self_test_duality()
        print()

    if args.npz is None:
        Gb, Gp, p_star, true_pi = built_in_self_test()
    else:
        Gb, Gp, p_star = load_npz_instance(args.npz)
        true_pi = None

    print()
    print("Solving reconstruction problem...")
    result = solve_reconstruction(
        Gb, Gp, p_star,
        time_limit_sec=args.time,
        workers=args.workers,
        log=args.log,
        w_encoding=args.w_encoding,
        certificate=args.certificate,
        rank_cuts=args.rank_cuts,
        row_weight_cuts=not args.no_row_weight_cuts,
        branch=args.branch,
        dualize=args.dualize,
        verbose=True,
    )

    if result is None:
        return 1

    pi_sol, U_sol = result

    print()
    print("Recovered pi:")
    print(pi_sol)

    if true_pi is not None:
        print()
        print("Original true pi used to generate p_star:")
        print(true_pi)
        print("Note: recovered pi need not equal true pi; many pi share "
              "the same pivot profile.")

    print()
    print("Verifying PRIMAL solution against original instance:")
    ok = verify_solution(
        Gb, Gp, p_star, pi_sol, U_sol,
        print_matrices=args.print_matrices,
    )
    return 0 if ok else 2


if __name__ == "__main__":
    sys.exit(main())