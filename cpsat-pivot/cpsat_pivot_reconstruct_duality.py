# Solver
# ============================================================

def _solve_single_instance(
    Gb: np.ndarray,
    Gp: np.ndarray,
    p_star: List[int],
    *,
    time_limit_sec: float,
    workers: int,
    log: bool,
    w_encoding: str,
    certificate: str,
    rank_cuts: str,
    row_weight_cuts: bool,
    branch: str,
    verbose: bool,
    hint_pi: Optional[List[int]] = None,
) -> Optional[Tuple[List[int], np.ndarray, str]]:
    model, variables = build_pivot_reconstruction_model(
        Gb, Gp, p_star,
        w_encoding=w_encoding,
        certificate=certificate,
        rank_cuts=rank_cuts,
        row_weight_cuts=row_weight_cuts,
        branch=branch,
        verbose=verbose,
    )

    pi_vars = variables["pi"]
    u_vars = variables["u"]
    k, n = gf2(Gb).shape

    if hint_pi is not None:
        for a in range(n):
            model.AddHint(pi_vars[a], int(hint_pi[a]))

    solver = cp_model.CpSolver()
    solver.parameters.max_time_in_seconds = float(time_limit_sec)
    solver.parameters.num_search_workers = int(workers)
    solver.parameters.log_search_progress = bool(log)

    status = solver.Solve(model)
    status_name = solver.StatusName(status)
    print(f"Solver status: {status_name}")

    if status not in (cp_model.FEASIBLE, cp_model.OPTIMAL):
        return None

    pi_sol = [solver.Value(pi_vars[a]) for a in range(n)]
    U_sol = np.zeros((k, k), dtype=np.uint8)
    for i in range(k):
        for r in range(k):
            U_sol[i, r] = solver.Value(u_vars[i, r]) & 1

    return pi_sol, U_sol, status_name


def solve_reconstruction(
    Gb: np.ndarray,
    Gp: np.ndarray,
    p_star: List[int],
    *,
    time_limit_sec: float = 60.0,
    workers: int = 8,
    log: bool = False,
    w_encoding: str = "auto",
    certificate: str = "pivot-only",
    rank_cuts: str = "span",
    row_weight_cuts: bool = True,
    branch: str = "popcount",
    dualize: str = "auto",
    hint_pi: Optional[List[int]] = None,
    verbose: bool = True,
) -> Optional[Tuple[List[int], Optional[np.ndarray]]]:
    """
    Solve the reconstruction problem, possibly on the dual instance.

    Returns (pi, U) where U certifies the instance that was actually
    solved (U is None when the dual was solved, since the returned pi
    is for the primal; the profile itself is re-verified numerically).
    """
    Gb = gf2(Gb)
    Gp = gf2(Gp)
    p_star = [int(x) for x in p_star]
    k, n = Gb.shape

    dualize = str(dualize).lower()
    if dualize not in {"auto", "always", "never"}:
        raise ValueError("dualize must be one of: auto, always, never.")

    polar_ok = is_standard_polar_matrix(Gp)

    if dualize == "always" and not polar_ok:
        raise ValueError("--dualize always requires standard polar Gp.")

    use_dual = False
    if polar_ok and 0 < n - k < n:
        if dualize == "always":
            use_dual = True
        elif dualize == "auto":
            use_dual = (n - k) < k  # strictly smaller dual instance

    if not use_dual:
        if verbose:
            print(f"Solving PRIMAL instance: n={n}, k={k}.")
        result = _solve_single_instance(
            Gb, Gp, p_star,
            time_limit_sec=time_limit_sec, workers=workers, log=log,
            w_encoding=w_encoding, certificate=certificate,
            rank_cuts=rank_cuts, row_weight_cuts=row_weight_cuts,
            branch=branch, verbose=verbose, hint_pi=hint_pi,
        )
        if result is None:
            return None
        pi_sol, U_sol, _ = result
        return pi_sol, U_sol

    # ---------------- dual path ----------------
    Hb, q_star = dualize_instance(Gb, p_star)
    if verbose:
        print(f"Matroid-duality reduction: primal (n={n}, k={k}) "
              f"-> dual (n={n}, k'={n-k}).")
        print(f"  dual target q_star = {q_star}")

    hint_sigma = None
    if hint_pi is not None:
        hint_sigma = list(reversed([int(x) for x in hint_pi]))

    result = _solve_single_instance(
        Hb, Gp, q_star,
        time_limit_sec=time_limit_sec, workers=workers, log=log,
        w_encoding=w_encoding, certificate=certificate,
        rank_cuts=rank_cuts, row_weight_cuts=row_weight_cuts,
        branch=branch, verbose=verbose, hint_pi=hint_sigma,
    )
    if result is None:
        return None

    sigma_sol, U_dual, _ = result

    # Verify the dual solution against the dual instance (with its U).
    print()
    print("Verifying DUAL solution against dual instance:")
    ok_dual = verify_solution(Hb, Gp, q_star, sigma_sol, U_dual)
    if not ok_dual:
        print("WARNING: dual solution failed dual verification.")
        return None

    pi_sol = primal_pi_from_dual_sigma(sigma_sol)
    return pi_sol, None


# ============================================================
# Verification
# ============================================================

def verify_solution(
    Gb: np.ndarray,
    Gp: np.ndarray,
    p_star: List[int],
    pi_sol: List[int],
    U_sol: Optional[np.ndarray] = None,
    *,
    print_matrices: bool = False,
) -> bool:
    Gb = gf2(Gb)
    Gp = gf2(Gp)
    p_star = [int(x) for x in p_star]
    k, n = Gb.shape

    piGb = Gb[:, pi_sol]
    W = gf2_matmul(piGb, Gp)
    actual_pivots = column_pivot_profile_gf2(W)

    print("Target pivot profile: ", p_star)
    print("Actual pivot profile: ", actual_pivots)

    ok_profile = (actual_pivots == p_star)
    print("Pivot profile check:", "PASS" if ok_profile else "FAIL")

    ok_cert = True
    if U_sol is not None:
        U_sol = gf2(U_sol)
        M = gf2_matmul(U_sol, W)

        ok_identity = all(
            int(M[i, p]) == (1 if i == ell else 0)
            for i in range(k)
            for ell, p in enumerate(p_star)
        )
        print("U-certificate identity check:", "PASS" if ok_identity else "FAIL")
        ok_cert = ok_identity

        if print_matrices:
            print("pi(Gb) =\n", piGb)
            print("W =\n", W)
            print("U =\n", U_sol)
            print("M = U W =\n", M)

    return ok_profile and ok_cert


# ============================================================
# Self-tests
# ============================================================

def self_test_duality(trials: int = 40, seed: int = 1) -> None:
    """
    Numerical check of the matroid-duality identity:

        p_star = Profile(pi(Gb) F)
            =>
        Profile(sigma(Hb) F) = q_star,  sigma = pi[::-1],
        q_star = sorted{n-1-j : j not in p_star}.

    Also checks the inverse mapping pi = sigma[::-1].
    """
    rng = np.random.default_rng(seed)
    checked = 0
    for m in (3, 4, 5):
        n = 2 ** m
        F = polar_matrix(m)
        for _ in range(trials):
            k = int(rng.integers(1, n))
            Gb = random_full_row_rank_binary_matrix(k, n, rng)
            pi = list(rng.permutation(n))
            p = column_pivot_profile_gf2(gf2_matmul(Gb[:, pi], F))
            if len(p) != k:
                raise RuntimeError("full-rank Gb must yield k pivots")

            Hb, q = dualize_instance(Gb, p)
            sigma = list(reversed(pi))
            q_check = column_pivot_profile_gf2(gf2_matmul(Hb[:, sigma], F))
            if q_check != q:
                raise AssertionError(
                    f"DUALITY CHECK FAILED at n={n}, k={k}:\n"
                    f"  pi = {pi}\n  p* = {p}\n"
                    f"  expected q* = {q}\n  got        = {q_check}"
                )
            if primal_pi_from_dual_sigma(sigma) != pi:
                raise AssertionError("pi <-> sigma mapping is not involutive")
            checked += 1
    print(f"[self-test] duality identity verified on {checked} random instances "
          f"(n in {{8,16,32}}).  PASS")


def built_in_self_test() -> Tuple[np.ndarray, np.ndarray, List[int], List[int]]:
    """
    Reachable test instance with k > n/2 so that the dual path is
    exercised under --dualize auto.
    """
    rng = np.random.default_rng(0)
    m = 4
    n = 2 ** m
    k = 10

    Gp = polar_matrix(m)
    Gb = random_full_row_rank_binary_matrix(k, n, rng)
    true_pi = list(rng.permutation(n))

    W_true = gf2_matmul(Gb[:, true_pi], Gp)
    p_star = column_pivot_profile_gf2(W_true)
    if len(p_star) != k:
        raise RuntimeError("Unexpected pivot profile length in self-test.")

    print("Built-in self-test instance:")
    print(f"  n = {n}, k = {k}  (k > n/2, dual path active under auto)")
    print(f"  true pi = {true_pi}")
    print(f"  p_star from true pi = {p_star}")
    return Gb, Gp, p_star, true_pi


def load_npz_instance(path: str) -> Tuple[np.ndarray, np.ndarray, List[int]]:
    data = np.load(path, allow_pickle=False)
    if "Gb" not in data or "Gp" not in data or "p_star" not in data:
        raise ValueError("npz file must contain arrays Gb, Gp, and p_star.")
    Gb = gf2(data["Gb"])
    Gp = gf2(data["Gp"])
    p_star = [int(x) for x in np.asarray(data["p_star"]).reshape(-1)]
    return Gb, Gp, p_star


